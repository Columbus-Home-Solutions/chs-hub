// ─── PUT /api/jobs/:id ────────────────────────────────────────────────────────

export async function handleJobUpdate(request: Request, env: Env, id: string): Promise<Response> {
  const guarded = await guard(request, env, [...WRITE_ROLES]);
  if (guarded instanceof Response) return guarded;
  const { user } = guarded;

  const body = await readJson(request);
  if (!body) return err(400, "bad_request", "Body must be JSON");

  if ("status" in body) {
    return err(
      400,
      "use_status_endpoint",
      "Status changes go through PUT /api/jobs/:id/status, which validates transitions.",
    );
  }

  const job = await env.DB.prepare(
    `SELECT id FROM jobs WHERE id = ? AND ${nativeJobSourceWhere()}`,
  )
    .bind(id)
    .first<{ id: string }>();
  if (!job) return err(404, "not_found", "Job not found.");

  const sets: string[] = [];
  const binds: unknown[] = [];

  if ("assigned_to" in body) {
    const raw = body.assigned_to;
    const assignedTo =
      raw === null || raw === undefined || raw === "" ? null : str(raw);
    if (assignedTo) {
      const userOk = await env.DB.prepare(
        "SELECT id FROM users WHERE id = ? AND is_active = 1",
      )
        .bind(assignedTo)
        .first<{ id: string }>();
      if (!userOk) {
        return err(400, "invalid_user", "Assigned user not found or inactive.");
      }
    }
    sets.push("assigned_to = ?");
    binds.push(assignedTo);
  }

  const editable: Record<string, "str"> = {
    title: "str",
    notes: "str",
    start_date: "str",
    target_end_date: "str",
    actual_end_date: "str",
    payer_id: "str",
  };
  for (const [field] of Object.entries(editable)) {
    if (field in body) {
      sets.push(`${field} = ?`);
      binds.push(str(body[field]));
    }
  }

  // Boolean toggle fields (0/1).
  if ("review_enabled" in body) {
    sets.push("review_enabled = ?");
    binds.push(body.review_enabled ? 1 : 0);
  }

  if (sets.length === 0) return err(400, "bad_request", "No editable fields provided.");

  sets.push("updated_at = ?");
  binds.push(new Date().toISOString());
  binds.push(id);

  await env.DB.prepare(`UPDATE jobs SET ${sets.join(", ")} WHERE id = ?`).bind(...binds).run();
  await logAudit(env, user.email, "job_updated", "job", id, {
    fields: [
      ...Object.keys(editable).filter((f) => f in body),
      ...("assigned_to" in body ? ["assigned_to"] : []),
      ...("review_enabled" in body ? ["review_enabled"] : []),
    ],
  });

  return handleJobDetail(env, id);
}

// ─── PUT /api/jobs/:id/review-received ────────────────────────────────────────

/**
 * Idempotent — marks review_received = 1 and stamps review_received_at.
 * Stops the follow-up sequence for this job on the next nightly sweep.
 * Auth: O/PM.
 */
export async function handleJobReviewReceived(request: Request, env: Env, id: string): Promise<Response> {
  const guarded = await guard(request, env, ["owner", "project_manager"] as const);
  if (guarded instanceof Response) return guarded;
  const { user } = guarded;

  const job = await env.DB.prepare(
    "SELECT id, review_received FROM jobs WHERE id = ?",
  ).bind(id).first<{ id: string; review_received: number }>();
  if (!job) return err(404, "not_found", "Job not found.");

  if (job.review_received) {
    return json({ ok: true, review_received: true, review_received_at: null, already_set: true });
  }

  await env.DB.prepare(
    `UPDATE jobs SET review_received = 1, review_received_at = datetime('now'), updated_at = ? WHERE id = ?`,
  ).bind(new Date().toISOString(), id).run();

  await logAudit(env, user.email, "job_review_received", "job", id, {});

  return json({ ok: true, review_received: true });
}

// ─── Close-eligibility check (shared by GET and gate inside PUT /status) ─────

interface EligibilityResult {
  eligible: boolean;
  checks: EligibilityCheck[];
}

async function computeCloseEligibility(env: Env, jobId: string): Promise<EligibilityResult> {
  const checks: EligibilityCheck[] = [];

  const jobRow = await env.DB.prepare(`SELECT billing_model FROM jobs WHERE id = ?`)
    .bind(jobId)
    .first<{ billing_model: string | null }>();
  const billingModel = (jobRow?.billing_model ?? "fixed_price").toLowerCase();

  // 1. invoices_paid — every non-void, non-draft invoice must be paid.
  const unpaidRows = (
    await env.DB.prepare(
      `SELECT invoice_number
         FROM invoices
        WHERE job_id = ?
          AND status NOT IN ('void', 'draft', 'paid')`,
    )
      .bind(jobId)
      .all<{ invoice_number: number | null }>()
  ).results ?? [];
  const unpaidLabels = unpaidRows.map((r) => invoiceLabel(r.invoice_number));
  checks.push({
    id: "invoices_paid",
    label: "All invoices paid",
    passed: unpaidRows.length === 0,
    detail:
      unpaidRows.length > 0
        ? `${unpaidRows.length} invoice(s) unpaid: ${unpaidLabels.join(", ")}`
        : null,
  });

  // 2. no_draft_invoices — no draft or sent (unresolved) invoices.
  const draftRow = await env.DB.prepare(
    `SELECT COUNT(*) AS n FROM invoices WHERE job_id = ? AND status IN ('draft', 'sent')`,
  )
    .bind(jobId)
    .first<{ n: number }>();
  checks.push({
    id: "no_draft_invoices",
    label: "No draft/unsent invoices",
    passed: (draftRow?.n ?? 0) === 0,
    detail: (draftRow?.n ?? 0) > 0 ? `${draftRow!.n} draft/sent invoice(s) not yet resolved` : null,
  });

  // 3. expenses_logged — at least one expense record exists.
  const expRow = await env.DB.prepare(
    `SELECT COUNT(*) AS n FROM expenses WHERE job_id = ?`,
  )
    .bind(jobId)
    .first<{ n: number }>();
  checks.push({
    id: "expenses_logged",
    label: "Expenses logged for job",
    passed: (expRow?.n ?? 0) > 0,
    detail: (expRow?.n ?? 0) === 0 ? "No expense records found — unusual for a real job" : null,
  });

  // 4. no_open_co — no change orders in draft or sent status.
  const coRow = await env.DB.prepare(
    `SELECT COUNT(*) AS n FROM change_orders WHERE job_id = ? AND status IN ('draft', 'sent')`,
  )
    .bind(jobId)
    .first<{ n: number }>();
  checks.push({
    id: "no_open_co",
    label: "No open change orders",
    passed: (coRow?.n ?? 0) === 0,
    detail: (coRow?.n ?? 0) > 0 ? `${coRow!.n} change order(s) awaiting signature or approval` : null,
  });

  // 5. punch_list_clear — no open punch-list tasks.
  const plRow = await env.DB.prepare(
    `SELECT COUNT(*) AS n FROM tasks WHERE job_id = ? AND is_punch_list = 1 AND status NOT IN ('complete', 'skipped')`,
  )
    .bind(jobId)
    .first<{ n: number }>();
  checks.push({
    id: "punch_list_clear",
    label: "Punch list complete",
    passed: (plRow?.n ?? 0) === 0,
    detail: (plRow?.n ?? 0) > 0 ? `${plRow!.n} open punch list item(s) remaining` : null,
  });

  // 6. Completion signal — billing-model specific.
  if (billingModel === "cost_plus") {
    const finalCycle = await env.DB.prepare(
      `SELECT id, status, invoice_id, reconciliation_invoice_id, reconciliation_date, cycle_number
         FROM billing_cycles
        WHERE job_id = ? AND is_final_cycle = 1
        ORDER BY cycle_number DESC
        LIMIT 1`,
    )
      .bind(jobId)
      .first<{
        id: string;
        status: string;
        invoice_id: string | null;
        reconciliation_invoice_id: string | null;
        reconciliation_date: string | null;
        cycle_number: number;
      }>();

    const invoiceIds = [finalCycle?.invoice_id, finalCycle?.reconciliation_invoice_id].filter(
      (id): id is string => !!id,
    );
    const cycleInvoices =
      invoiceIds.length > 0
        ? ((
            await env.DB.prepare(
              `SELECT id, invoice_number, status FROM invoices WHERE id IN (${invoiceIds.map(() => "?").join(", ")})`,
            )
              .bind(...invoiceIds)
              .all<{ id: string; invoice_number: number | null; status: string }>()
          ).results ?? [])
        : [];

    checks.push(buildCostPlusFinalCycleCheck(finalCycle ?? null, cycleInvoices));
  } else {
    const finalRow = await env.DB.prepare(
      `SELECT invoice_number, status FROM invoices WHERE job_id = ? AND invoice_type = 'final' ORDER BY created_at DESC LIMIT 1`,
    )
      .bind(jobId)
      .first<{ invoice_number: number | null; status: string }>();
    checks.push(buildFixedPriceFinalInvoiceCheck(finalRow ?? null));
  }

  return { eligible: checks.every((c) => c.passed), checks };
}

