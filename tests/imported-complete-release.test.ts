describe("complete imports stay on the jobs surfaces", () => {
  const jobsApi = read("../src/routes/jobs-api.ts");
  const search = read("../frontend/src/components/layout/GlobalSearch.tsx");

  it("filters header search after the board predicate, with no 8-row cap first", () => {
    const list = jobsApi.slice(jobsApi.indexOf("export async function handleJobList"));
    expect(list).toContain('url.searchParams.get("q")');
    expect(list).toContain("jobMatchesQuery");
    expect(list.indexOf("jobMatchesQuery")).toBeLessThan(list.indexOf(".slice(0, 25)"));
    expect(search).not.toContain(".slice(0, 8)");
    expect(search).toContain("/api/jobs?q=");
  });

  it("returns cancelled jobs beside the board, not as a column", () => {
    const pipeline = jobsApi.slice(
      jobsApi.indexOf("export async function handleJobPipeline"),
      jobsApi.indexOf("export async function handleJobDetail"),
    );
    expect(pipeline).toContain('card.status === "cancelled"');
    expect(pipeline).toContain("cancelled,");
    const nav = SIDEBAR_NAV.find((item) => item.id === "jobs");
    const cancelled = nav?.children?.find((child) => child.label === "Cancelled");
    expect(cancelled?.href).toContain("?status=cancelled");
    const labels = nav?.children?.map((child) => child.label) ?? [];
    const completed = nav?.children?.find((child) => child.label === "Completed");
    expect(completed?.href).toContain("?status=complete");
    expect(labels.indexOf("Completed")).toBe(labels.indexOf("Closed") - 1);
    expect(nav?.children?.find((child) => child.label === "Active")?.href).not.toContain("status=");
    expect(nav?.children?.find((child) => child.label === "Every Job")?.href).toContain("?status=all");
    expect(labels).not.toContain("Needs Reconciliation");
    expect(labels).not.toContain("All Jobs");
    const jobsPath = "/app/jobs";
    expect(completed?.activeTest?.(jobsPath, "stage=complete")).toBe(true);
    expect(completed?.activeTest?.(jobsPath, "status=complete")).toBe(true);
    expect(nav?.children?.find((child) => child.label === "Active")?.activeTest?.(jobsPath, "stage=complete")).toBe(false);
    expect(nav?.children?.find((child) => child.label === "Active")?.activeTest?.(jobsPath, "")).toBe(true);
    expect(nav?.children?.find((child) => child.label === "In Progress")?.activeTest?.(jobsPath, "status=in_progress")).toBe(true);
  });

  it("keeps detail on the same job query with the id swap", () => {
    expect(jobsApi).toContain('const JOB_LIST_WHERE = `${boardJobWhere("j")} AND (${NON_TEST_CLIENT})`');
    expect(jobsApi).toContain("WHERE j.id = ?");
  });
});

describe("quiet completion for jobber imports", () => {
  const jobsApi = read("../src/routes/jobs-api.ts");
  const punch = read("../src/routes/punch-lists.ts");
  const completion = read("../src/routes/completion-package.ts");

  it("skips every automatic complete effect after the status write and audit", () => {
    const status = jobsApi.slice(jobsApi.indexOf("─── PUT /api/jobs/:id/status"));
    const gate = status.indexOf('target === "complete" && skipImportedCompletionEffects(job))');
    expect(status).toContain("SELECT id, status, source, data_source FROM jobs");
    expect(status).not.toContain("skipImportedCompletionEffects(job.source)");
    expect(gate).toBeGreaterThan(status.indexOf("job_status_changed"));
    expect(gate).toBeLessThan(status.indexOf("triggerJobStatusChanged"));
    expect(gate).toBeLessThan(status.indexOf("maybeGenerateJobCompletionPost"));
    expect(gate).toBeLessThan(status.indexOf("warranty_certificate"));
    expect(gate).toBeLessThan(status.indexOf("checkAndFireLienWaiverForJob"));
    expect(status).toContain("actual_end_date = COALESCE(actual_end_date, ?)");
  });

  it("uses the same check when punch lists close a job", () => {
    const fn = punch.slice(punch.indexOf("async function maybeCompleteJobAfterPunchListsClosed"));
    expect(fn).toContain("SELECT status, source, data_source FROM jobs");
    expect(fn).not.toContain("skipImportedCompletionEffects(job.source)");
    expect(fn.indexOf("skipImportedCompletionEffects(job))")).toBeLessThan(
      fn.indexOf("maybeAutoGenerateDocument"),
    );
  });

  it("leaves the manual completion-package send and review request in place", () => {
    expect(completion).toContain("sendImmediateReviewRequest");
    expect(completion).toContain("jobberQuietSendBlock");
    expect(completion).not.toContain("skipImportedCompletionEffects");
    const send = completion.slice(completion.indexOf("export async function handleCompletionPackageSend"));
    expect(send).toContain("formatDatePlusFiveYears");
    expect(send).toContain("warrantyExpirationDate");
    expect(send).toContain("ensureJobPortalToken");
    expect(send).toContain("warranty_expiration = COALESCE(NULLIF(TRIM(warranty_expiration), ''), ?)");
    expect(send).not.toContain("formatDatePlusOneYear");
  });
});

