// ─── PUT /api/jobs/:id/status ─────────────────────────────────────────────────

export async function handleJobStatus(request: Request, env: Env, id: string, ctx: ExecutionContext): Promise<Response> {
  const guarded = await guard(request, env, [...WRITE_ROLES]);
  if (guarded instanceof Response) return guarded;
  const { user } = guarded;

  const body = await readJson(request);
  if (!body) return err(400, "bad_request", "Body must be JSON");
  const target = str(body.status);
  if (!target || !(target in STATUS_INDEX)) {
    return err(400, "bad_request", `status must be one of: ${JOB_STATUSES.join(", ")}`);
  }

  const job = await env.DB.prepare(
    `SELECT id, status FROM jobs WHERE id = ? AND ${nativeJobSourceWhere()}`,
  )
    .bind(id)
    .first<{ id: string; status: string }>();
  if (!job) return err(404, "not_found", "Job not found.");

  const from = job.status;
  if (from === target) return err(400, "no_change", "Job is already in that status.");

  const fromIdx = STATUS_INDEX[from] ?? -1;
  const toIdx = STATUS_INDEX[target];
  const isForward = fromIdx >= 0 && toIdx > fromIdx;
  const isAllowedBackward = BACKWARD_EXCEPTIONS.has(`${from}>${target}`);
  if (!isForward && !isAllowedBackward) {
    return err(
      400,
      "illegal_transition",
      `Cannot move from ${from} to ${target}. Jobs move forward only (allowed backward: in_progress→scheduled, complete→punch_list).`,
    );
  }

  // Gate → complete: all punch-list items must be complete (§6.9).
  if (target === "complete") {
    const open = await env.DB.prepare(
      "SELECT COUNT(*) AS n FROM tasks WHERE job_id = ? AND is_punch_list = 1 AND status != 'complete'",
    )
      .bind(id)
      .first<{ n: number }>();
    if ((open?.n ?? 0) > 0) {
      return err(
        409,
        "open_punch_list",
        `Cannot complete: ${open!.n} punch-list item(s) still open.`,
      );
    }
  }

  // Gate → closed: full 6-check reconciliation (Sprint 25 §D1B).
  // Returns 422 with structured checks array so the frontend can display exactly
  // what is blocking closure. Backend is authoritative — the frontend gate is UX polish.
  if (target === "closed") {
    const eligibility = await computeCloseEligibility(env, id);
    if (!eligibility.eligible) {
      return json({ error: "Job cannot be closed", checks: eligibility.checks }, { status: 422 });
    }
  }

  const nowIso = new Date().toISOString();
  // actual_end_date is stamped when the job first reaches complete.
  const setActualEnd = target === "complete";
  if (target === "closed") {
    const dates = await env.DB.prepare("SELECT actual_end_date FROM jobs WHERE id = ?")
      .bind(id)
      .first<{ actual_end_date: string | null }>();
    const completionDate = dates?.actual_end_date?.slice(0, 10) ?? nowIso.slice(0, 10);
    const warrantyExp = warrantyExpirationDate(completionDate);
    await env.DB.prepare(
      `UPDATE jobs
          SET status = ?, updated_at = ?, warranty_expiration = ?,
              actual_end_date = COALESCE(actual_end_date, ?)
        WHERE id = ?`,
    )
      .bind(target, nowIso, warrantyExp, completionDate, id)
      .run();
  } else {
    await env.DB.prepare(
      `UPDATE jobs SET status = ?, updated_at = ?${setActualEnd ? ", actual_end_date = COALESCE(actual_end_date, ?)" : ""} WHERE id = ?`,
    )
      .bind(...(setActualEnd ? [target, nowIso, nowIso.slice(0, 10), id] : [target, nowIso, id]))
      .run();
  }

  await logAudit(env, user.email, "job_status_changed", "job", id, { from, to: target });
  triggerJobStatusChanged(env, id, from, target);

  // Sprint 16 — Social Media auto-gen seam. On reaching `complete`, draft a
  // pending_approval job-completion post if the job has social-ready photos
  // (else notify "flag photos?"). NEVER auto-publishes; non-fatal so a social
  // hiccup can't block the status change.
  if (target === "complete") {
    await maybeGenerateJobCompletionPost(env, id, user.email).catch((e) =>
      console.error("[jobs-api] social auto-gen failed:", (e as Error).message),
    );
  }

  // Sprint 20 — Auto-generate contract document on deposit_paid; warranty cert on complete.
  // Non-blocking: doc gen failure must never roll back the status change.
  if (target === "deposit_paid") {
    // Determine contract template from billing_model
    const jobForBilling = await env.DB.prepare(
      "SELECT billing_model FROM jobs WHERE id = ?",
    )
      .bind(id)
      .first<{ billing_model: string | null }>();
    const billingModel = jobForBilling?.billing_model ?? "fixed_price";
    const contractTemplate =
      billingModel === "cost_plus" ? "cost_plus_agreement" : "service_agreement";
    // NOTE: trade_by_trade → service_agreement (confirmed default; flag for Tony in report-back)
    const skipAutogen = await shouldSkipContractAutogen(env, id, contractTemplate);
    if (skipAutogen) {
      console.log(
        `[AUTOTRIGGER] jobs-api deposit_paid — skip ${contractTemplate} (estimate contract already signed)`,
      );
    } else {
      console.log(`[AUTOTRIGGER] jobs-api deposit_paid — jobId=${id} template=${contractTemplate}`);
      ctx.waitUntil(
        maybeAutoGenerateDocument(env, {
          jobId: id,
          templateType: contractTemplate,
          triggerEvent: "job_deposit_paid",
        }).catch((e) =>
          console.error("[jobs-api] doc auto-gen (deposit_paid) failed:", (e as Error).message),
        ),
      );
    }
    scheduleWorkingAgreementGeneration(env, id, ctx);
  }

  if (target === "complete") {
    console.log(`[AUTOTRIGGER] jobs-api complete — jobId=${id}`);
    ctx.waitUntil(
      (async () => {
        await maybeAutoGenerateDocument(env, {
          jobId: id,
          templateType: "warranty_certificate",
          triggerEvent: "job_complete",
        });
        // Companion fancy visual warranty (same trigger; does not replace the personalized cert).
        const { maybeAutoGenerateFancyWarranty } = await import("../lib/warranty-fancy.js");
        await maybeAutoGenerateFancyWarranty(env, id, "job_complete");
        // If final payment already settled before complete, generate the lien waiver now.
        await checkAndFireLienWaiverForJob(env, id);
      })().catch((e) =>
        console.error("[jobs-api] doc auto-gen (complete) failed:", (e as Error).message),
      ),
    );
  }

  return handleJobDetail(env, id);
}

